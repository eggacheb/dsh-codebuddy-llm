export type LocaleKey = keyof typeof zh

export type Translate = (key: LocaleKey, params?: Record<string, string | number>) => string

/** Bind the runtime dictionary and fill `{name}` placeholders (missing ones stay verbatim). */
export function translator(locale: LocaleService): Translate {
  const lookup = locale.bind(NS)
  return (key, params) => lookup(key).replace(/\{(\w+)\}/g, (match, name: string) => params !== undefined && name in params ? String(params[name]) : match)
}
